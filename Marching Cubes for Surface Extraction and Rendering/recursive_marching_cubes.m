% The objective of this script is to run a recursive version of the
% Marching Cubes algorithm. The input data is the data matrix, which 
% contains the hip density values. The output is the corresponding
% to the boundary surfaces.  

% The recursive_marching_cubes function is a wrapper function. 

function [triangles, normals] = recursive_marching_cubes(data, isovalue)
    % data: 3D matrix of scalars
    % isovalue: Intesity threshold, in our case it represents a bone density
    dimX = size(data, 1);
    dimY = size(data, 2);
    dimZ = size(data, 3);
    % Start with the full volume. 
    % Note: We use global indices [Start, End]
    [triangles, normals] = recurse_block(data, isovalue, [1, dimX], [1, dimY], [1, dimZ]);
end

% The recursion_block() function below is the recursion block. 
% It navigates in the cube by performing divide and conquer. 
% It calls the process_single_cube() function, explained in part 3.  

function [tris, norms] = recurse_block(data, iso, arrX, arrY, arrZ)
    % data: Reference to the huge matrix (MATLAB passes by ref if not modified)
    % iso: The isovalue.
    % arrX: Arrays for the X axis; arrY for Y-axis; arrZ for Z-axis 
    
    % 1. EXTRACT LOCAL BLOCK BOUNDS
    x1 = arrX(1); x2 = arrX(2);
    y1 = arrY(1); y2 = arrY(2);
    z1 = arrZ(1); z2 = arrZ(2);
    
    % 2. MIN/MAX CHECK STEP
    % We extract the sub-block values to check min/max
    sub_block = data(x1:x2, y1:y2, z1:z2);
    min_val = min(sub_block(:));
    max_val = max(sub_block(:));
    
    tris = [];
    norms = [];
    
    % If the surface does not pass through this block, reject.
    if (max_val < iso) || (min_val > iso)
        return; 
    end
    
    % 3. BASE CASE: SINGLE CUBE
    % If the block is 1x1x1 (meaning indices are [i, i+1]), process it.
    dx = x2 - x1;
    dy = y2 - y1;
    dz = z2 - z1;
    
    if (dx == 1 && dy == 1 && dz == 1)
        % CALLING MY MARCHING FUNCTION
        % We pass the top-left-front coordinate (x1, y1, z1)
        [tris, norms] = process_single_cube(data, iso, x1, y1, z1);
        return;
    end
    
    % 4. RECURSIVE STEP (The "Divide")
    % We split the longest axes. 
    
    % Calculate Midpoints (using floor)
    midX = floor((x1 + x2) / 2);
    midY = floor((y1 + y2) / 2);
    midZ = floor((z1 + z2) / 2);
    
    % Define ranges.
    % Left block ends at midX, Right block starts at midX.
    rangesX = { [x1, midX], [midX, x2] };
    rangesY = { [y1, midY], [midY, y2] };
    rangesZ = { [z1, midZ], [midZ, z2] };
    
    % Handle cases where dimension is already 1 (don't split further)
    if dx == 1, rangesX = { [x1, x2] }; end
    if dy == 1, rangesY = { [y1, y2] }; end
    if dz == 1, rangesZ = { [z1, z2] }; end

    % Loop through subdivisions (up to 8 children)
    for i = 1:length(rangesX)
        for j = 1:length(rangesY)
            for k = 1:length(rangesZ)
                [new_tris, new_norms] = recurse_block(data, iso, rangesX{i}, rangesY{j}, rangesZ{k});
                % Append results
                tris = [tris; new_tris];
                norms = [norms; new_norms];
            end
        end
    end
end

function [t, n] = process_single_cube(data, iso, x, y, z)
    % Initialize t,n 
    t = []; 
    n = []; 

    % 1. Retrieving the 8 corner values
    corners = data(x:x+1,y:y+1,z:z+1)
   
    % 2. Defining the relative position of each summits
    
    % For pos_offsets, I used the same convention we saw in class. This is 
    % very important, since we later use the canonical matrix to look up 
    % each of the configurations. 
    
    % For now, we assume that the imported "data" is oriented in a 
    % similar way, with x,y,z being respectively right, up, forward directions. 
    % This can be corrected later, in accordance with the visualization we obtain. 
    
    pos_offsets = [
        0 0 0;  % v1 (Bit 1)
        1 0 0;  % v2 (Bit 2)
        1 1 0;  % v3 (Bit 3)
        0 1 0;  % v4 (Bit 4)
        0 0 1;  % v5 (Bit 5)
        1 0 1;  % v6 (Bit 6)
        1 1 1;  % v7 (Bit 7)
        0 1 1   % v8 (Bit 8)
    ];

    % Mapping the previously defined corners to their scalar values in the 
    % correct order. 
    
    cube = [
        corners(1,1,1); % v1 (x,y,z) --> origin
        corners(2,1,1); % v2 (x+1,y,z) --> +1 right
        corners(2,2,1); % v3
        corners(1,2,1); % v4 (x,y+1,z) --> +1 upwards
        corners(1,1,2); % v5 (x,y,z+1) --> +1 forward
        corners(2,1,2); % v6
        corners(2,2,2); % v7
        corners(1,2,2)  % v8 
    ];
    cube = double(cube);  
    % 3. Calculating the cube's index (8-bits)
    cube_index = 0;
    for i = 1:8
        if cube(i) > iso
            cube_index = cube_index + 2^(i-1);
        end
    end
    % 4. Call to the Look-Up Table, to know which edges intersect
    tri_table = get_tri_table();
    edges = tri_table(cube_index + 1, :);
   
    % If the cube is strictly outside or inside the surface, return nothing
    if edges(1) == 0 %my table 
        return;
    end
    
    % 5. Interpolating intersection points of surface with the cube's edges 
    
    % Calculating coordinates of the vertices on the given cube
    vert_list = zeros(12, 3);
    
    % Defining edge connections, represented by pairs of vertices 
    % e.g. : Edge 1 connects v1 and v2 
   
    edge_connections = [
        1 2; 2 3; 3 4; 4 1; % Bottom edges 
        5 6; 6 7; 7 8; 8 5; % Top edges 
        1 5; 2 6; 3 7; 4 8  % Vertical edges
    ];

    % We calculate the coordinates of each intersection point using linear
    % interpolation
    % Technically, we could optimize this step by only calculating the
    % intersections for the "concerned" edges
    for i = 1:12
        vA = edge_connections(i, 1); % Index of the 1st summit
        vB = edge_connections(i, 2); % Index of the 2nd summit
        
        % Global positions of the edge's summits (add x,y,z)
        p1 = [x, y, z] + pos_offsets(vA, :);
        p2 = [x, y, z] + pos_offsets(vB, :);
        
        val1 = cube(vA);
        val2 = cube(vB);
        
        % Linear interpolation : P = P1 + (iso - V1)(P2 - P1) / (V2 - V1)
        if abs(val2 - val1) > 1e-5 % Avoid division by zero
            mu = (iso - val1) / (val2 - val1);
        else
            mu = 0.5;
        end
        vert_list(i, :) = p1 + mu * (p2 - p1);
    end

    % 6. Triangle creation
    % 'edges' contains a sequence of edges, ex: [0 8 3, -1, ...]

    k = 1;
    while k <= length(edges) && edges(k) ~= 0       
        e1 = edges(k);
        e2 = edges(k+1);
        e3 = edges(k+2);
        
        % Retrieve the points calculated earlier
        p1 = vert_list(e1, :);
        p2 = vert_list(e2, :);
        p3 = vert_list(e3, :);
        
        % Add triangle to the list
        t = [t; p1, p2, p3]; 
        
        % Calculating a vector "normal" to the triangle
        U = p2 - p1;
        V = p3 - p1;
        
        normal_vec = cross(U, V);
        mag = norm(normal_vec);  % ? this calls the function
        if mag > 1e-10
            normal_vec = normal_vec / mag;
        else
            normal_vec = [0, 0, 1]; % fallback
        end
       
        n = [n; repmat(normal_vec, 3, 1)];        
        k = k + 3;
    end
    end

